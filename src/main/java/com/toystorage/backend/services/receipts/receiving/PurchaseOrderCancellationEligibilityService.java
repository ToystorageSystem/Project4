package com.toystorage.backend.services.receipts.receiving;

import com.toystorage.backend.entity.receipts.PurchaseOrders;
import com.toystorage.backend.enums.suppliers.SupplierInvoiceStatus;
import com.toystorage.backend.exceptions.BadRequest;
import com.toystorage.backend.repository.receipts.PurchaseOrderItemRepository;
import com.toystorage.backend.repository.receipts.receiving.GoodsReceiptRepository;
import com.toystorage.backend.repository.suppliers.SupplierInvoiceRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

@Service
@RequiredArgsConstructor
public class PurchaseOrderCancellationEligibilityService {

    private final PurchaseOrderItemRepository itemRepository;
    private final GoodsReceiptRepository receiptRepository;
    private final SupplierInvoiceRepository invoiceRepository;

    // Tránh hủy đơn khi kho hoặc kế toán đã bắt đầu xử lý chứng từ.
    // Kể cả GR đã hủy vẫn cần rà soát thủ công trước khi đóng PO.
    public void assertNoReceivingOrInvoices(PurchaseOrders order) {
        Long id = order.getId();

        boolean received = itemRepository.findByPurchaseOrder_IdOrderByIdAsc(id)
                .stream()
                .anyMatch(item -> item.getReceivedQuantity() != null && item.getReceivedQuantity() > 0);
        if (received) {
            throw new BadRequest("Purchase order has received quantities and cannot be cancelled");
        }
        if (receiptRepository.existsByPurchaseOrder_Id(id)) {
            throw new BadRequest("Purchase order has linked goods receipts; resolve them before cancellation");
        }
        if (invoiceRepository.existsByPurchaseOrder_IdAndStatusNot(id, SupplierInvoiceStatus.CANCELLED)) {
            throw new BadRequest("Purchase order has an active supplier invoice; resolve it before cancellation");
        }
    }

    public void assertNotAutoGenerated(PurchaseOrders order) {
        if (order.getOrderCode() != null && order.getOrderCode().startsWith("PO-AUTO-")) {
            throw new BadRequest("Auto-generated purchase orders require manual review before cancellation");
        }
    }
}
