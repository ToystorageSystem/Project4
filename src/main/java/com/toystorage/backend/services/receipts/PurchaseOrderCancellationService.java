package com.toystorage.backend.services.receipts;

import com.toystorage.backend.dto.request.receipts.RequestPurchaseOrderCancellation;
import com.toystorage.backend.dto.request.receipts.ReviewPurchaseOrderCancellation;
import com.toystorage.backend.dto.response.receipts.PurchaseOrderCancellationResponse;
import com.toystorage.backend.entity.receipts.PurchaseOrderCancellationRequests;
import com.toystorage.backend.entity.receipts.PurchaseOrders;
import com.toystorage.backend.entity.users.ActivityLogs;
import com.toystorage.backend.entity.users.Users;
import com.toystorage.backend.enums.receipts.PurchaseOrderCancellationStatus;
import com.toystorage.backend.enums.receipts.PurchaseOrderStatus;
import com.toystorage.backend.enums.users.ActivityAction;
import com.toystorage.backend.enums.users.ActivityEntityType;
import com.toystorage.backend.exceptions.BadRequest;
import com.toystorage.backend.exceptions.Forbidden;
import com.toystorage.backend.exceptions.NotFound;
import com.toystorage.backend.exceptions.Unauthorized;
import com.toystorage.backend.repository.receipts.PurchaseOrderCancellationRepository;
import com.toystorage.backend.repository.receipts.PurchaseOrderRepository;
import com.toystorage.backend.repository.users.ActivityLogRepository;
import com.toystorage.backend.repository.users.UserRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Objects;

@Service
@RequiredArgsConstructor
public class PurchaseOrderCancellationService {

    private final PurchaseOrderCancellationRepository requestRepository;
    private final PurchaseOrderRepository orderRepository;
    private final PurchaseOrderCancellationEligibilityService eligibilityService;
    private final UserRepository userRepository;
    private final ActivityLogRepository activityLogRepository;

    @Transactional
    public PurchaseOrderCancellationResponse requestCancellation(
            Long orderId, RequestPurchaseOrderCancellation payload
    ) {
        Users actor = getCurrentUser();
        PurchaseOrders order = lockOrder(orderId);
        requireCreator(order, actor);
        if (order.getStatus() != PurchaseOrderStatus.ORDERED) {
            throw new BadRequest("Only ORDERED purchase orders can request cancellation");
        }
        if (!Boolean.TRUE.equals(payload.getSupplierAgreed())) {
            throw new BadRequest("Supplier cancellation agreement must be confirmed");
        }
        String reason = requireReason(payload.getReason(), 10);
        eligibilityService.assertNotAutoGenerated(order);
        eligibilityService.assertNoReceivingOrInvoices(order);
        if (requestRepository.existsByPurchaseOrder_IdAndStatus(orderId, PurchaseOrderCancellationStatus.PENDING)) {
            throw new BadRequest("A pending cancellation request already exists for this purchase order");
        }

        PurchaseOrderCancellationRequests request = PurchaseOrderCancellationRequests.builder()
                .purchaseOrder(order)
                .requestedBy(actor)
                .status(PurchaseOrderCancellationStatus.PENDING)
                .reason(reason)
                .supplierAgreed(true)
                .requestedAt(LocalDateTime.now())
                .build();
        request = requestRepository.save(request);
        audit(actor, ActivityAction.UPDATE, order, "cancellationRequest=NONE",
                "cancellationRequest=PENDING, requestId=" + request.getId() + ", reason=" + reason);
        return toResponse(request);
    }

    @Transactional(readOnly = true)
    public List<PurchaseOrderCancellationResponse> listForOrder(Long orderId) {
        Users actor = getCurrentUser();
        PurchaseOrders order = orderRepository.findById(orderId)
                .orElseThrow(() -> new NotFound("Purchase order not found"));
        if (!isManagerOrAdmin() && !Objects.equals(actor.getId(), order.getCreatedBy().getId())) {
            throw new Forbidden("You cannot view another user's cancellation requests");
        }
        return requestRepository.findByPurchaseOrder_IdOrderByRequestedAtDesc(orderId)
                .stream().map(this::toResponse).toList();
    }

    @Transactional(readOnly = true)
    public List<PurchaseOrderCancellationResponse> listForManager(PurchaseOrderCancellationStatus status) {
        List<PurchaseOrderCancellationRequests> requests = status == null
                ? requestRepository.findAllByOrderByRequestedAtDesc()
                : requestRepository.findByStatusOrderByRequestedAtDesc(status);
        return requests.stream().map(this::toResponse).toList();
    }

    @Transactional
    public PurchaseOrderCancellationResponse approve(Long requestId, ReviewPurchaseOrderCancellation payload) {
        Users actor = getCurrentUser();
        Long orderId = requestRepository.findOrderIdByRequestId(requestId)
                .orElseThrow(() -> new NotFound("Cancellation request not found"));
        PurchaseOrders order = lockOrder(orderId);
        PurchaseOrderCancellationRequests request = requestRepository.findForReviewUpdate(requestId)
                .orElseThrow(() -> new NotFound("Cancellation request not found"));
        assertPendingAndDifferentReviewer(request, actor);
        if (order.getStatus() != PurchaseOrderStatus.ORDERED) {
            throw new BadRequest("Purchase order is no longer ORDERED; cancellation approval is blocked");
        }
        eligibilityService.assertNotAutoGenerated(order);
        eligibilityService.assertNoReceivingOrInvoices(order);

        order.setStatus(PurchaseOrderStatus.CANCELLED);
        order.setCancelReason(request.getReason());
        request.setStatus(PurchaseOrderCancellationStatus.APPROVED);
        request.setReviewedBy(actor);
        request.setReviewedAt(LocalDateTime.now());
        request.setDecisionNote(normalizeNote(payload));
        orderRepository.save(order);
        requestRepository.save(request);
        audit(actor, ActivityAction.CANCEL, order, "status=ORDERED, cancellationRequest=PENDING",
                "status=CANCELLED, cancellationRequest=APPROVED, requestId=" + requestId
                        + ", cancelReason=" + request.getReason());
        return toResponse(request);
    }

    @Transactional
    public PurchaseOrderCancellationResponse reject(Long requestId, ReviewPurchaseOrderCancellation payload) {
        Users actor = getCurrentUser();
        Long orderId = requestRepository.findOrderIdByRequestId(requestId)
                .orElseThrow(() -> new NotFound("Cancellation request not found"));
        PurchaseOrders order = lockOrder(orderId);
        PurchaseOrderCancellationRequests request = requestRepository.findForReviewUpdate(requestId)
                .orElseThrow(() -> new NotFound("Cancellation request not found"));
        assertPendingAndDifferentReviewer(request, actor);
        String note = requireReason(payload == null ? null : payload.getNote(), 10);
        request.setStatus(PurchaseOrderCancellationStatus.REJECTED);
        request.setReviewedBy(actor);
        request.setReviewedAt(LocalDateTime.now());
        request.setDecisionNote(note);
        requestRepository.save(request);
        audit(actor, ActivityAction.REJECT, order,
                "cancellationRequest=PENDING, requestId=" + requestId,
                "cancellationRequest=REJECTED, requestId=" + requestId + ", note=" + note);
        return toResponse(request);
    }

    private void requireCreator(PurchaseOrders order, Users actor) {
        if (!Objects.equals(order.getCreatedBy().getId(), actor.getId()) && !hasRole("ROLE_ROLE-ADMIN")) {
            throw new Forbidden("Only the purchase order creator can request cancellation");
        }
    }

    private void assertPendingAndDifferentReviewer(PurchaseOrderCancellationRequests request, Users actor) {
        if (request.getStatus() != PurchaseOrderCancellationStatus.PENDING) {
            throw new BadRequest("Cancellation request is no longer pending");
        }
        if (Objects.equals(request.getRequestedBy().getId(), actor.getId())) {
            throw new Forbidden("A user cannot approve or reject their own cancellation request");
        }
    }

    private String requireReason(String text, int minLength) {
        String normalized = text == null ? "" : text.trim();
        if (normalized.length() < minLength || normalized.length() > 1000) {
            throw new BadRequest("Reason must contain " + minLength + " to 1000 characters");
        }
        return normalized;
    }

    private String normalizeNote(ReviewPurchaseOrderCancellation payload) {
        String text = payload == null ? null : payload.getNote();
        if (text == null || text.isBlank()) return null;
        if (text.trim().length() > 1000) throw new BadRequest("Decision note is too long");
        return text.trim();
    }

    private PurchaseOrders lockOrder(Long orderId) {
        return orderRepository.findForCancellationUpdate(orderId)
                .orElseThrow(() -> new NotFound("Purchase order not found"));
    }

    private Users getCurrentUser() {
        Authentication auth = SecurityContextHolder.getContext().getAuthentication();
        if (auth == null || !auth.isAuthenticated() || "anonymousUser".equals(auth.getPrincipal())) {
            throw new Unauthorized("User is not authenticated");
        }
        return userRepository.findByEmail(auth.getName())
                .orElseThrow(() -> new NotFound("Authenticated user not found"));
    }

    private boolean isManagerOrAdmin() {
        return hasRole("ROLE_ROLE-BIZ-OPS") || hasRole("ROLE_ROLE-ADMIN");
    }

    private boolean hasRole(String role) {
        Authentication auth = SecurityContextHolder.getContext().getAuthentication();
        return auth != null && auth.getAuthorities().stream().anyMatch(a -> role.equals(a.getAuthority()));
    }

    private void audit(Users actor, ActivityAction action, PurchaseOrders order, String oldValue, String newValue) {
        activityLogRepository.save(ActivityLogs.builder()
                .user(actor)
                .action(action)
                .entityType(ActivityEntityType.PURCHASE_ORDER)
                .entityId(order.getId())
                .oldValue(oldValue)
                .newValue(newValue)
                .build());
    }

    private PurchaseOrderCancellationResponse toResponse(PurchaseOrderCancellationRequests request) {
        PurchaseOrders order = request.getPurchaseOrder();
        Users reviewer = request.getReviewedBy();
        return PurchaseOrderCancellationResponse.builder()
                .id(request.getId())
                .purchaseOrderId(order.getId())
                .orderCode(order.getOrderCode())
                .supplierName(order.getSupplier() == null ? null : order.getSupplier().getName())
                .purchaseOrderStatus(order.getStatus().name())
                .status(request.getStatus().name())
                .reason(request.getReason())
                .supplierAgreed(request.getSupplierAgreed())
                .requestedById(request.getRequestedBy().getId())
                .requestedByName(request.getRequestedBy().getName())
                .requestedAt(request.getRequestedAt())
                .reviewedById(reviewer == null ? null : reviewer.getId())
                .reviewedByName(reviewer == null ? null : reviewer.getName())
                .reviewedAt(request.getReviewedAt())
                .decisionNote(request.getDecisionNote())
                .build();
    }
}
