/**
 * Easy one-sheet import for Business Operations.
 * Each row creates one Product with one supplier; codes are generated by ProductService.
 * Legacy two-sheet Excel imports continue to use ProductExcelImportService unchanged.
 */
@Service
@RequiredArgsConstructor
public class ProductSimpleExcelImportService {
    private static final List<String> HEADERS = List.of(
            "Barcode", "Product Name", "Category", "Base Unit", "Selling Price (VND)",
            "Supplier Name", "Supplier Phone (optional)", "Purchase Price (VND)",
            "Minimum Order Quantity", "Brand (optional)");
    private static final int MAX_ROWS = 300;
    private static final long MAX_BYTES = 5L * 1024 * 1024;

    private final ProductService productService;
    private final ProductRepository productRepository;
    private final SupplierRepository supplierRepository;
    private final CategoryRepository categoryRepository;
    private final BrandRepository brandRepository;

    public ProductImportPreviewResponse preview(MultipartFile file) {
        return parse(file);
    }

    @Transactional
    public ProductImportResultResponse importProducts(MultipartFile file) {
        ProductImportPreviewResponse result = parse(file);
        if (result.getInvalidRows() > 0) {
            throw new BadRequest("Please correct the invalid rows and preview the file again before importing");
        }
        List<ProductResponse> created = new ArrayList<>();
        for (ProductImportRowResponse row : result.getRows()) {
            CreateProductRequest product = new CreateProductRequest();
            product.setProductCode(null); // Generated by ProductService
            product.setBarcode(row.getBarcode());
            product.setName(row.getName());
            product.setCategoryId(row.getCategoryId());
            product.setBrandId(row.getBrandId()); // optional: null when the Brand column is empty
            product.setBaseUnit(row.getBaseUnit());
            product.setSellingPrice(row.getSellingPrice());
            product.setPurchasePrice(row.getPurchasePrice());
            product.setRequestReason("Imported from Excel");

            CreateProductWithSupplierRequest request = new CreateProductWithSupplierRequest();
            request.setProduct(product);
            request.setSupplierName(row.getSupplierName());
            request.setSupplierPhone(row.getSupplierPhone());
            request.setMinimumOrderQuantity(row.getMinimumOrderQuantity());
            request.setLeadTimeDays(0);
            created.add(productService.createProductWithSupplier(request));
        }
        return ProductImportResultResponse.builder()
                .totalRows(result.getTotalRows())
                .importedRows(created.size())
                .products(created)
                .build();
    }

    private ProductImportPreviewResponse parse(MultipartFile file) {
        if (file == null || file.isEmpty()) throw new BadRequest("Please choose an Excel file");
        String filename = Optional.ofNullable(file.getOriginalFilename()).orElse("").toLowerCase(Locale.ROOT);
        if (!filename.endsWith(".xlsx") && !filename.endsWith(".xls")) {
            throw new BadRequest("Upload an .xlsx or .xls file");
        }
        if (file.getSize() > MAX_BYTES) throw new BadRequest("Excel file must be smaller than 5 MB");

        try (Workbook workbook = WorkbookFactory.create(file.getInputStream())) {
            if (workbook.getNumberOfSheets() == 0) throw new BadRequest("The Excel file is empty");
            Sheet sheet = workbook.getSheetAt(0);
            DataFormatter formatter = new DataFormatter();
            Row header = sheet.getRow(0);
            if (header == null) throw new BadRequest("Header row is missing. Download and use the template");
            for (int i = 0; i < HEADERS.size(); i++) {
                String actual = cell(header, i, formatter);
                if (!HEADERS.get(i).equals(actual)) {
                    throw new BadRequest("Invalid column " + (i + 1) + ": expected '" + HEADERS.get(i)
                            + "'. Please download and use the template");
                }
            }
            for (int i = HEADERS.size(); i < header.getLastCellNum(); i++) {
                if (!cell(header, i, formatter).isEmpty()) {
                    throw new BadRequest("Unexpected column after Brand (optional). Use the template");
                }
            }
            if (sheet.getLastRowNum() > MAX_ROWS + 20) {
                throw new BadRequest("Import at most " + MAX_ROWS + " products per file");
            }

            List<ProductImportRowResponse> rows = new ArrayList<>();
            Map<String, ProductImportRowResponse> firstPair = new HashMap<>();
            for (int r = 1; r <= sheet.getLastRowNum(); r++) {
                Row excelRow = sheet.getRow(r);
                if (empty(excelRow, formatter)) continue;
                if (rows.size() >= MAX_ROWS) throw new BadRequest("Import at most " + MAX_ROWS + " products per file");
                ProductImportRowResponse row = read(excelRow, r + 1, formatter);
                rows.add(row);
                String barcode = normalize(row.getBarcode());
                String supplier = normalize(row.getSupplierName());
                if (!barcode.isEmpty() && !supplier.isEmpty()) {
                    String key = barcode + "\u0000" + supplier;
                    ProductImportRowResponse previous = firstPair.putIfAbsent(key, row);
                    if (previous != null) {
                        mark(row, "This Barcode + Supplier is already listed on row " + previous.getRowNumber());
                        mark(previous, "This Barcode + Supplier is repeated on row " + row.getRowNumber());
                    }
                }
            }
            if (rows.isEmpty()) throw new BadRequest("There are no products to import");
            int valid = (int) rows.stream().filter(ProductImportRowResponse::isValid).count();
            return ProductImportPreviewResponse.builder()
                    .totalRows(rows.size()).validRows(valid)
                    .invalidRows(rows.size() - valid).rows(rows).build();
        } catch (BadRequest ex) {
            throw ex;
        } catch (Exception ex) {
            throw new BadRequest("Unable to read Excel file. Please use the downloaded template");
        }
    }

    private ProductImportRowResponse read(Row excelRow, int rowNo, DataFormatter formatter) {
        List<String> errors = new ArrayList<>();
        String barcode = cell(excelRow, 0, formatter);
        String name = cell(excelRow, 1, formatter);
        String categoryText = cell(excelRow, 2, formatter);
        String unit = cell(excelRow, 3, formatter);
        BigDecimal selling = positiveMoney(cell(excelRow, 4, formatter), "Selling Price", errors);
        String supplierName = cell(excelRow, 5, formatter);
        String supplierPhone = cell(excelRow, 6, formatter);
        BigDecimal purchase = positiveMoney(cell(excelRow, 7, formatter), "Purchase Price", errors);
        Integer minimum = positiveInt(cell(excelRow, 8, formatter), errors);
        String brandText = cell(excelRow, 9, formatter);

        if (barcode.isEmpty() || barcode.length() > 100) errors.add("Barcode is required (max 100 characters)");
        if (name.isEmpty() || name.length() > 200) errors.add("Product Name is required (max 200 characters)");
        if (unit.isEmpty() || unit.length() > 30) errors.add("Base Unit is required (max 30 characters)");
        if (supplierName.isEmpty() || supplierName.length() > 200) errors.add("Supplier Name is required (max 200 characters)");
        if (!supplierPhone.isEmpty() && !supplierPhone.matches("\\+?[0-9]{9,15}")) {
            errors.add("Supplier Phone must contain 9-15 digits, optionally starting with +");
        }

        List<Categories> categories = categoryRepository.findByStatusOrderByNameAsc(CommonStatus.ACTIVE)
                .stream().filter(c -> c.getName().equalsIgnoreCase(categoryText)).toList();
        Long categoryId = null;
        if (categories.size() == 1) categoryId = categories.get(0).getId();
        else errors.add("Category is not an active category name: " + categoryText);

        // Brand is optional: empty -> no brand; otherwise it must be exactly one ACTIVE brand name
        Long brandId = null;
        if (!brandText.isEmpty()) {
            List<Brands> brands = brandRepository.findByStatusOrderByNameAsc(CommonStatus.ACTIVE)
                    .stream().filter(b -> b.getName().equalsIgnoreCase(brandText)).toList();
            if (brands.size() == 1) brandId = brands.get(0).getId();
            else errors.add("Brand is not an active brand name: " + brandText);
        }

        if (!barcode.isEmpty() && productRepository.existsByBarcodeAndOwningSupplierIsNull(barcode)) {
            errors.add("Barcode belongs to a legacy product with no confirmed supplier. Review it before importing");
        }
        if (!supplierName.isEmpty()) {
            List<Suppliers> suppliers = supplierRepository.findByNameIgnoreCase(supplierName);
            if (suppliers.size() > 1) {
                errors.add("Multiple suppliers share this name; resolve the name first");
            } else if (suppliers.size() == 1) {
                Suppliers existing = suppliers.get(0);
                if (existing.getStatus() != CommonStatus.ACTIVE) errors.add("Supplier is inactive");
                else if (!barcode.isEmpty() &&
                        (productRepository.existsByBarcodeAndOwningSupplier_IdAndIdNot(
                                barcode, existing.getId(), -1L)
                        || productRepository.existsLinkedBarcodeForSupplier(barcode, existing.getId(), null))) {
                    errors.add("This supplier already has a product with this barcode");
                }
            }
        }

        return ProductImportRowResponse.builder()
                .rowNumber(rowNo).barcode(barcode).name(name).categoryId(categoryId)
                .categoryName(categoryText)
                .brandId(brandId).brandName(brandText.isEmpty() ? null : brandText).baseUnit(unit.toUpperCase(Locale.ROOT))
                .sellingPrice(selling).purchasePrice(purchase)
                .supplierName(supplierName).supplierPhone(supplierPhone.isEmpty() ? null : supplierPhone)
                .minimumOrderQuantity(minimum).errors(errors).valid(errors.isEmpty()).build();
    }

    private BigDecimal positiveMoney(String text, String label, List<String> errors) {
        try {
            BigDecimal value = new BigDecimal(text.replace(",", ""));
            if (value.compareTo(BigDecimal.ZERO) <= 0 || value.scale() > 2) throw new NumberFormatException();
            return value;
        } catch (Exception ex) {
            errors.add(label + " must be greater than zero (up to 2 decimal places)");
            return null;
        }
    }

    private Integer positiveInt(String text, List<String> errors) {
        try {
            int value = new BigDecimal(text).intValueExact();
            if (value <= 0) throw new NumberFormatException();
            return value;
        } catch (Exception ex) {
            errors.add("Minimum Order Quantity must be a positive whole number");
            return null;
        }
    }

    private String cell(Row row, int index, DataFormatter formatter) {
        return row == null || row.getCell(index) == null ? ""
                : formatter.formatCellValue(row.getCell(index)).trim();
    }

    private boolean empty(Row row, DataFormatter formatter) {
        for (int col = 0; col < HEADERS.size(); col++) {
            if (!cell(row, col, formatter).isEmpty()) return false;
        }
        return true;
    }

    private String normalize(String value) {
        return value == null ? "" : value.trim().toLowerCase(Locale.ROOT);
    }

    private void mark(ProductImportRowResponse row, String error) {
        row.getErrors().add(error);
        row.setValid(false);
    }

    /** Returns a template with English columns and dropdowns for existing categories/suppliers/brands. */
    public byte[] template() {
        try (XSSFWorkbook workbook = new XSSFWorkbook(); ByteArrayOutputStream stream = new ByteArrayOutputStream()) {
            Sheet products = workbook.createSheet("Products");
            Sheet lookup = workbook.createSheet("Options");
            CellStyle headerStyle = workbook.createCellStyle();
            Font font = workbook.createFont();
            font.setBold(true);
            font.setColor(IndexedColors.WHITE.getIndex());
            headerStyle.setFont(font);
            headerStyle.setFillForegroundColor(IndexedColors.DARK_BLUE.getIndex());
            headerStyle.setFillPattern(FillPatternType.SOLID_FOREGROUND);
            headerStyle.setWrapText(true);

            Row heading = products.createRow(0);
            heading.setHeightInPoints(30);
            for (int i = 0; i < HEADERS.size(); i++) {
                Cell cell = heading.createCell(i);
                cell.setCellValue(HEADERS.get(i));
                cell.setCellStyle(headerStyle);
                products.setColumnWidth(i, Math.min(30, Math.max(17, HEADERS.get(i).length() + 4)) * 256);
            }
            products.createFreezePane(0, 1);
            products.setAutoFilter(new org.apache.poi.ss.util.CellRangeAddress(0, 300, 0, HEADERS.size() - 1));

            List<String> categories = categoryRepository.findByStatusOrderByNameAsc(CommonStatus.ACTIVE)
                    .stream().map(Categories::getName).toList();
            List<String> suppliers = supplierRepository.findByStatusOrderByNameAsc(CommonStatus.ACTIVE)
                    .stream().map(Suppliers::getName).toList();
            for (int i = 0; i < categories.size(); i++) lookup.createRow(i + 1).createCell(0).setCellValue(categories.get(i));
            for (int i = 0; i < suppliers.size(); i++) {
                Row row = lookup.getRow(i + 1);
                if (row == null) row = lookup.createRow(i + 1);
                row.createCell(1).setCellValue(suppliers.get(i));
            }
            List<String> brands = brandRepository.findByStatusOrderByNameAsc(CommonStatus.ACTIVE)
                    .stream().map(Brands::getName).toList();
            for (int i = 0; i < brands.size(); i++) {
                Row row = lookup.getRow(i + 1);
                if (row == null) row = lookup.createRow(i + 1);
                row.createCell(2).setCellValue(brands.get(i));
            }
            if (!categories.isEmpty()) addList(workbook, products, "CategoryOptions", "A", categories.size(), 2);
            if (!suppliers.isEmpty()) addList(workbook, products, "SupplierOptions", "B", suppliers.size(), 5);
            if (!brands.isEmpty()) addList(workbook, products, "BrandOptions", "C", brands.size(), 9);
            workbook.setSheetHidden(workbook.getSheetIndex(lookup), true);

            workbook.write(stream);
            return stream.toByteArray();
        } catch (Exception ex) {
            throw new BadRequest("Unable to generate the Excel template");
        }
    }

    private void addList(XSSFWorkbook workbook, Sheet products, String name, String lookupColumn,
                         int count, int productColumn) {
        Name named = workbook.createName();
        named.setNameName(name);
        named.setRefersToFormula("'Options'!$" + lookupColumn + "$2:$" + lookupColumn + "$" + (count + 1));
        DataValidationHelper helper = products.getDataValidationHelper();
        DataValidationConstraint rule = helper.createFormulaListConstraint(name);
        CellRangeAddressList addresses = new CellRangeAddressList(1, 300, productColumn, productColumn);
        DataValidation validation = helper.createValidation(rule, addresses);
        validation.setShowErrorBox(false); // Allow users to type new Supplier names.
        products.addValidationData(validation);
    }
}
