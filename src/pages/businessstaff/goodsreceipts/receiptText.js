export function formatReceiptMoney(value) {
  const amount = Number(value);
  return Number.isFinite(amount)
    ? `${new Intl.NumberFormat("en-GB", { maximumFractionDigits: 2 }).format(amount)} VND`
    : "—";
}

export function formatReceiptDate(value) {
  if (!value) return "—";
  const dt = new Date(value);
  return Number.isNaN(dt.getTime()) ? String(value) : dt.toLocaleString("en-GB");
}

